#!/usr/bin/env node
// Read metadata only: never initialize plugins or invoke Docusaurus code generation.
// These installed-framework APIs keep IDs, locale fallback and version discovery in
// sync with the build. Run nav:test when upgrading Docusaurus (internal API surface).
const path = require('node:path');
const {loadSiteConfig} = require('@docusaurus/core/lib/server/config');
const {loadI18n} = require('@docusaurus/core/lib/server/i18n');
const {getLocaleConfig, normalizeUrl} = require('@docusaurus/utils');
const {getTagsFile} = require('@docusaurus/utils-validation');
const {validateOptions} = require('@docusaurus/plugin-content-docs/lib/options.js');
const {readVersionsMetadata} = require('@docusaurus/plugin-content-docs/lib/versions/version.js');
const {readVersionDocs, processDocMetadata} = require('@docusaurus/plugin-content-docs/lib/docs.js');
const {loadSidebarsFile} = require('@docusaurus/plugin-content-docs/lib/sidebars/index.js');
const {normalizeSidebars} = require('@docusaurus/plugin-content-docs/lib/sidebars/normalization.js');
const {validateSidebars} = require('@docusaurus/plugin-content-docs/lib/sidebars/validation.js');

function errorMessage(error) {
  return error.message + (error.cause ? `: ${errorMessage(error.cause)}` : '');
}

function docsOptions(siteConfig, siteDir) {
  const presets = siteConfig.presets.filter((preset) => {
    const name = Array.isArray(preset) ? preset[0] : preset;
    return typeof name === 'string' &&
      (name === 'classic' || name.includes('@docusaurus/preset-classic'));
  });
  if (presets.length !== 1 || presets[0][1]?.docs === false) {
    throw new Error('Navigation validation expects one classic preset with docs enabled.');
  }
  const options = validateOptions({
    options: presets[0][1]?.docs ?? {},
    validate: (schema, value) => {
      const result = schema.validate(value);
      if (result.error) throw result.error;
      return result.value;
    },
  });
  if (typeof options.sidebarPath !== 'string') {
    throw new Error('Configure sidebarPath for directly maintained navigation.');
  }
  options.id = 'default';
  options.sidebarPath = path.resolve(siteDir, options.sidebarPath);
  return options;
}

function checkMembership(docs, sidebars, sidebarPath, expectedRoot) {
  const errors = [];
  const byId = new Map();
  for (const doc of docs) {
    if (byId.has(doc.id)) {
      errors.push(`${doc.source}: duplicate document ID "${doc.id}" (also ${byId.get(doc.id).source})`);
    } else {
      byId.set(doc.id, doc);
    }
  }
  const homepage = byId.get('index');
  if (!homepage || homepage.draft) {
    errors.push('Homepage: expected published document with exact ID "index".');
  } else if (homepage.unlisted || homepage.permalink !== expectedRoot) {
    errors.push(`${homepage.source}: homepage "index" must be listed and resolve to "${expectedRoot}"; got "${homepage.permalink}".`);
  }
  const memberships = new Map();
  function target(id, location, member) {
    const doc = byId.get(id);
    if (!doc || doc.draft) {
      errors.push(`${location}: target "${id}" ${doc ? 'is a production draft' : 'does not exist'}.`);
    }
    if (member) {
      if (memberships.has(id)) {
        errors.push(`${location}: duplicate membership for "${id}" (also ${memberships.get(id)}). Use type: "ref" for cross-references.`);
      } else memberships.set(id, location);
    }
  }
  function visit(items, location) {
    items.forEach((item, index) => {
      const at = `${location}[${index}]`;
      if (item.type === 'doc' || item.type === 'ref') {
        target(item.id, at, item.type === 'doc');
      } else if (item.type === 'category') {
        if (item.link?.type === 'doc') target(item.link.id, `${at}.link`, true);
        visit(item.items, `${at}.items`);
      } else if (item.type === 'autogenerated') {
        errors.push(`${at}: autogenerated items are not supported in directly maintained navigation.`);
      }
      // link/html/generated-index are supported discovery items, not doc membership.
    });
  }
  for (const [name, items] of Object.entries(sidebars)) {
    visit(items, `${sidebarPath}:${name}`);
  }
  for (const doc of docs) {
    if (!doc.draft && !doc.unlisted && doc.id !== 'index' && !memberships.has(doc.id)) {
      errors.push(`${doc.source}: published document "${doc.id}" has no sidebar membership.`);
    }
  }
  return errors;
}

async function validateNavigation(siteDir) {
  siteDir = path.resolve(siteDir);
  const {siteConfig} = await loadSiteConfig({siteDir});
  const options = docsOptions(siteConfig, siteDir);
  const errors = [];
  const checked = [];
  for (const locale of siteConfig.i18n.locales) {
    const i18n = await loadI18n({siteDir, config: siteConfig, currentLocale: locale,
      automaticBaseUrlLocalizationDisabled: false});
    const localeConfig = getLocaleConfig(i18n);
    const context = {
      siteDir, i18n, baseUrl: localeConfig.baseUrl,
      localizationDir: path.resolve(siteDir, i18n.path, localeConfig.path),
      siteConfig: {...siteConfig, baseUrl: localeConfig.baseUrl, url: localeConfig.url},
    };
    const versions = await readVersionsMetadata({context, options});
    for (const versionMetadata of versions) {
      const scope = `[${locale}/${versionMetadata.versionName}]`;
      try {
        const tagsFile = await getTagsFile({contentPaths: versionMetadata, tags: options.tags});
        const files = await readVersionDocs(versionMetadata, options);
        const docs = [];
        for (const docFile of files.sort((a, b) => a.source.localeCompare(b.source))) {
          try {
            docs.push(await processDocMetadata({docFile, versionMetadata, context,
              options, env: 'production', tagsFile}));
          } catch (error) {
            errors.push(`${scope} ${errorMessage(error)}`);
          }
        }
        const sidebarPath = versionMetadata.sidebarFilePath;
        const sidebars = normalizeSidebars(await loadSidebarsFile(sidebarPath));
        // Validate each item separately to preserve its actionable sidebar location.
        function validateItems(items, location) {
          items.forEach((item, index) => {
            const at = `${location}[${index}]`;
            try {
              validateSidebars({item: [{...item, ...(item.type === 'category' ? {items: []} : {})}]});
            } catch (error) {
              throw new Error(`${at}: ${errorMessage(error)}`);
            }
            if (item.type === 'category') validateItems(item.items, `${at}.items`);
          });
        }
        for (const [name, items] of Object.entries(sidebars)) validateItems(items, `${sidebarPath}:${name}`);
        // Each version has its own root (and locales have localized base URLs).
        errors.push(...checkMembership(docs, sidebars, sidebarPath, normalizeUrl([versionMetadata.path, '/']))
          .map((error) => `${scope} ${error}`));
        // The active version's homepage must also be the site's locale root.
        if (versionMetadata.isLast && versionMetadata.path !== context.baseUrl) {
          errors.push(`${scope} Homepage: docs root "${versionMetadata.path}" must match site root "${context.baseUrl}".`);
        }
        checked.push(`${scope} ${docs.length} documents`);
      } catch (error) {
        errors.push(`${scope} ${versionMetadata.sidebarFilePath}: ${errorMessage(error)}`);
      }
    }
  }
  return {errors, checked};
}

async function main() {
  if (process.argv.length > 2) throw new Error('Usage: node scripts/validate-navigation.js (no options; read-only)');
  const {errors, checked} = await validateNavigation(path.resolve(__dirname, '..'));
  if (errors.length) {
    console.error(`Navigation validation failed:\n${errors.join('\n')}`);
    process.exitCode = 1;
  } else console.log(`Navigation valid: ${checked.join('; ')}.`);
}
if (require.main === module) main().catch((error) => {
  console.error(`Navigation validation failed: ${errorMessage(error)}`);
  process.exitCode = 1;
});
module.exports = {validateNavigation};
